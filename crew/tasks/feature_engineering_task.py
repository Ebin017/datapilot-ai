from crewai import Task

from crew.tools.feature_engineering_tool import (
    FeatureEngineeringTool,
)


def create_feature_engineering_task(agent) -> Task:

    return Task(
        description=(
            "Perform feature engineering on the cleaned dataset "
            "using the AnalysisPlan stored in the shared "
            "ProjectContext.\n\n"

            "The AnalysisPlan must already exist in "
            "ProjectContext before this task is executed.\n\n"

            "Use the Feature Engineering Tool to:\n"
            "- Separate the target variable from the features\n"
            "- Remove columns that should be excluded\n"
            "- Encode categorical features according to the plan\n"
            "- Encode the target when required\n"
            "- Scale numerical features according to the plan\n\n"

            "Do not load the dataset again.\n"
            "Do not generate a new analysis plan.\n"
            "Do not provide arguments to the Feature Engineering Tool.\n\n"

            "The tool reads the dataset and AnalysisPlan directly "
            "from the shared ProjectContext and stores the processed "
            "features and target in FeatureEngineeringResult."
        ),

        expected_output=(
            "A concise confirmation containing the processed "
            "feature shape, target shape, and total number of "
            "features generated by the Feature Engineering Tool."
        ),

        agent=agent,

        tools=[
            FeatureEngineeringTool(),
        ],
    )